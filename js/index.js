function loadProductDetails() {
  const selectedProduct = JSON.parse(
    localStorage.getItem("selectedProduct")
  );

  if (!selectedProduct) return;

  const mainImg = document.getElementById("mainImg");

  if (!mainImg) return;

  mainImg.src = selectedProduct.mainImage;
  mainImg.alt = selectedProduct.name;

  // Update product information
  const nameElement = document.querySelector("h3.py-4");
  const priceElement = document.querySelector("h2");
  const categoryElement = document.querySelector("h6");

  if (nameElement) nameElement.textContent = selectedProduct.name;
  if (priceElement) priceElement.textContent = selectedProduct.price;
  if (categoryElement) {
    categoryElement.textContent = `Home / ${selectedProduct.category}`;
  }

  // Create a gallery container beneath the main image
  let galleryContainer = document.getElementById("productGallery");

  if (!galleryContainer) {
    galleryContainer = document.createElement("div");
    galleryContainer.id = "productGallery";
    galleryContainer.className = "product-gallery";

    mainImg.insertAdjacentElement("afterend", galleryContainer);
  }

  galleryContainer.innerHTML = "";

  // Include the main image and any additional gallery images
  const images = [
    ...new Set([
      selectedProduct.mainImage,
      ...(selectedProduct.gallery || [])
    ])
  ].filter(Boolean);

  images.forEach((imageSrc, index) => {
    const thumbnail = document.createElement("img");

    thumbnail.src = imageSrc;
    thumbnail.alt = `${selectedProduct.name} view ${index + 1}`;
    thumbnail.className = "small-img";
    thumbnail.tabIndex = 0;
    thumbnail.setAttribute("role", "button");

    if (index === 0) {
      thumbnail.classList.add("active");
    }

    function selectImage() {
      mainImg.src = imageSrc;

      galleryContainer.querySelectorAll(".small-img")
        .forEach(img => img.classList.remove("active"));

      thumbnail.classList.add("active");
    }

    thumbnail.addEventListener("click", selectImage);

    thumbnail.addEventListener("keydown", (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        selectImage();
      }
    });

    galleryContainer.appendChild(thumbnail);
  });

  // Update product rating if available
  const stars = document.querySelectorAll(".star i");

  if (typeof selectedProduct.rating === "number") {
    stars.forEach((star, index) => {
      star.className = index < selectedProduct.rating
        ? "fa-solid fa-star"
        : "fa-regular fa-star";
    });
  }
}


document.addEventListener("DOMContentLoaded", function () {
  const MainImg = document.getElementById("mainImg");
  const smallImgs = document.getElementsByClassName("small-img");

  // Function to update product info based on image source
  function updateProductInfo(imgSrc) {
    // Extract product ID from image path
    const productId = imgSrc.split("/").pop().split(".")[0];

    // Check if product exists in our product database
    if (products[productId]) {
      const product = products[productId];

      // Update main image
      MainImg.src = imgSrc;

      // Update product details
      document.querySelector("h3.py-4").textContent = product.name;
      document.querySelector("h2").textContent = product.price;
      document.querySelector("span").textContent = product.description;
      document.querySelector("h6").textContent = `Home / ${product.category}`;

      // Update product rating stars
      const stars = document.querySelectorAll(".star i");
      stars.forEach((star, index) => {
        if (index < product.rating) {
          star.className = "fa-solid fa-star";
        } else {
          star.className = "fa-regular fa-star";
        }
      });

      // Store selected product in localStorage
      localStorage.setItem("selectedProduct", JSON.stringify(product));
    }
  }
  // Add click handlers to all small images
  for (let i = 0; i < smallImgs.length; i++) {
    smallImgs[i].onclick = function () {
      updateProductInfo(this.src);
    };
  }
});
function updateCartCounter() {
  const cartItems = JSON.parse(localStorage.getItem("cartItems")) || [];
  const cartLink = document.querySelector('a[href="cart.html"] i');

  if (cartLink) {
    const existingCounter = cartLink.parentNode.querySelector(".cart-counter");
    if (existingCounter) {
      existingCounter.remove();
    }

    const totalItems = cartItems.reduce(
      (total, item) => total + item.quantity,
      0
    );

    if (totalItems > 0) {
      const counterSpan = document.createElement("span");
      counterSpan.className = "cart-counter badge badge-danger";
      counterSpan.style.cssText = `
                position: absolute; 
                top: -8px; 
                right: -8px; 
                background-color: #03346f; 
                color: white; 
                border-radius: 50%; 
                padding: 2px 6px; 
                font-size: 0.7rem; 
                line-height: 1;
                min-width: 20px;
                text-align: center;
            `;
      counterSpan.textContent = totalItems;
      cartLink.parentNode.style.position = "relative";
      cartLink.parentNode.appendChild(counterSpan);
    }
  }
}

function addToCart(product, size, quantity) {
  const cartItems = JSON.parse(localStorage.getItem("cartItems")) || [];

  const cartItem = {
    name: product.name,
    price: product.price,
    size: size,
    quantity: quantity,
    image: product.mainImage,
  };

  const existingItemIndex = cartItems.findIndex(
    (item) => item.name === cartItem.name && item.size === cartItem.size
  );

  if (existingItemIndex > -1) {
    cartItems[existingItemIndex].quantity += quantity;
  } else {
    cartItems.push(cartItem);
  }

  localStorage.setItem("cartItems", JSON.stringify(cartItems));
  updateCartCounter();
}

